const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const path = require('node:path');
const mod = new Module(__filename, module);
mod.require = (id) => id.endsWith('service.enum') ? {ServiceStatus: {DELETED: 'DELETED'}} : require(id);
mod._compile(ts.transpileModule(fs.readFileSync(path.join(__dirname, '../libs/components/workspace/serviceOptionRules.ts'), 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS}}).outputText, __filename);
const {getOptionScope, isValidOptionDraft} = mod.exports;
const base = {_id: 'base', memberId: 'doctor', departmentId: 'department', serviceType: 'type', serviceStatus: 'ACTIVE'};
const rows = [base, {...base, _id: 'inactive', serviceStatus: 'INACTIVE', packageBaseServiceId: 'base'}, {...base, _id: 'other-dept', departmentId: 'other'}, {...base, _id: 'fourth', departmentId: 'other', serviceStatus: 'INACTIVE'}, {...base, _id: 'deleted', serviceStatus: 'DELETED'}, {...base, _id: 'other-doctor', memberId: 'other'}, {...base, _id: 'other-type', serviceType: 'other'}];
let scope = getOptionScope(base, rows);
assert.equal(scope.capacity, 4, 'Inactive and other-department services consume capacity');
assert.deepEqual(scope.variants.map(row => row._id), ['base', 'inactive'], 'Only explicitly linked packages are a booking family');
assert.equal(getOptionScope(null, rows).capacity, 0);
assert.equal(getOptionScope(base, [{...base, serviceTitle: 'Updated'}]).base.serviceTitle, 'Updated', 'Refreshed base replaces stale selected data');
const draft = {serviceTitle: 'Consultation', serviceDesc: 'Clinical details', servicePrice: '7000', serviceDuration: '30'};
assert.ok(isValidOptionDraft(draft, 'KRW'));
for (const change of [{serviceTitle: '  '}, {serviceDesc: '  '}, {servicePrice: ''}, {servicePrice: 'Infinity'}, {servicePrice: '-1'}, {servicePrice: '7000.5'}, {serviceDuration: '0'}, {serviceDuration: '30.5'}, {serviceDuration: '1441'}]) assert.equal(isValidOptionDraft({...draft, ...change}, 'KRW'), false, JSON.stringify(change));
assert.ok(isValidOptionDraft({...draft, servicePrice: '7.25'}, 'USD'));
assert.equal(isValidOptionDraft({...draft, servicePrice: '7.251'}, 'USD'), false);
assert.ok(isValidOptionDraft({...draft, servicePrice: '0', serviceDuration: '1440'}, 'KRW'));
console.log('OPTION_MANAGEMENT_VERIFIED 17 checks');
